test('isolates hashing records and recovers from failed Hot Key saves', async ({ page }) => {
  test.setTimeout(90000)
  await page.addInitScript(() => {
    const original = IDBDatabase.prototype.transaction
    const flags = { fail: false }
    IDBDatabase.prototype.transaction = function (...args: Parameters<typeof original>) {
      if (flags.fail && this.name === 'system-design-algorithm-labs' && args[1] === 'readwrite') throw new DOMException('test quota', 'QuotaExceededError')
      return original.apply(this, args)
    }
    Object.assign(window, { hotStorageFlags: flags })
  })
  await page.goto('/practice/consistent-hashing')
  await page.getByRole('combobox', { name: '你的预测', exact: true }).selectOption('uncertain')
  await page.getByRole('button', { name: '+ 新增 node-e', exact: true }).click()
  await page.getByRole('button', { name: '运行并记录', exact: true }).click()
  await expect(page.getByTestId('algorithm-save-status')).toHaveText('已保存到此浏览器')
  await open(page)
  await page.getByRole('button', { name: '自由探索', exact: true }).click()
  await page.evaluate(() => { (window as unknown as { hotStorageFlags: { fail: boolean } }).hotStorageFlags.fail = true })
  await page.getByRole('button', { name: '运行热点实验', exact: true }).click()
  await expect(page.getByTestId('hot-save-status')).toContainText('未保存')
  await expect(page.getByTestId('hot-history').locator('details')).toHaveCount(1)
  await page.evaluate(() => { (window as unknown as { hotStorageFlags: { fail: boolean } }).hotStorageFlags.fail = false })
  await page.getByRole('button', { name: '重试保存热点实验', exact: true }).click()
  await expect(page.getByTestId('hot-save-status')).toHaveText('已保存到此浏览器')
  await page.getByRole('link', { name: '一致性哈希', exact: true }).click()
  await expect(page.getByTestId('algorithm-history').locator('details')).toHaveCount(1)
  await expect(page.getByTestId('algorithm-feedback')).toContainText('操作完成，继续用证据解释')
  await open(page)
  await expect(page.getByTestId('hot-history').locator('details')).toHaveCount(1)
  await expect(page.getByTestId('hot-feedback')).toContainText('运行证据已记录')
})
