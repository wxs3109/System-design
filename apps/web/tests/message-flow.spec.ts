test('persists partial packets and independent lesson records, with save failure recovery', async ({ page }) => {
  test.setTimeout(60000)
  await page.addInitScript(() => {
    const original = IDBDatabase.prototype.transaction
    const flags = { fail: false }
    IDBDatabase.prototype.transaction = function (...args: Parameters<typeof original>) {
      if (flags.fail && this.name === 'system-design-algorithm-labs' && args[1] === 'readwrite') throw new DOMException('test quota', 'QuotaExceededError')
      return original.apply(this, args)
    }
    Object.assign(window, { messageStorageFlags: flags })
  })
  await open(page)
  await click(page, '只提交业务任务'); await click(page, '发送事件 event-1')
  await expect(page.getByTestId('message-save-status')).toHaveText('当前操作已保存')
  await page.reload()
  await expect(page.getByRole('button', { name: '接纳 publication-1', exact: true })).toBeEnabled()
  await click(page, '清空消息实验')
  await page.getByRole('combobox', { name: '消费者处理策略', exact: true }).selectOption('atomic')
  await page.evaluate(() => { (window as unknown as { messageStorageFlags: { fail: boolean } }).messageStorageFlags.fail = true })
  await click(page, '运行完整消息故障示例'); await click(page, '核对并保存消息结果')
  await expect(page.getByTestId('message-save-status')).toContainText('未保存')
  await expect(page.getByTestId('message-history').locator('details')).toHaveCount(1)
  await page.evaluate(() => { (window as unknown as { messageStorageFlags: { fail: boolean } }).messageStorageFlags.fail = false })
  await click(page, '重试保存消息实验')
  await expect(page.getByTestId('message-save-status')).toHaveText('当前操作已保存')
  await open(page, 'transactional-outbox')
  await expect(page.getByTestId('message-history').locator('details')).toHaveCount(0)
  await open(page)
  await expect(page.getByTestId('message-history').locator('details')).toHaveCount(1)
  await expect(page.getByTestId('message-effects')).toHaveText('1')
  await click(page, '清空消息实验')
  await page.getByRole('button', { name: '只提交业务任务', exact: true }).focus(); await page.keyboard.press('Enter')
  await expect(page.getByTestId('message-tasks')).toHaveText('1')
})
