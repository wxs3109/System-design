import { expect, test, type Page } from '@playwright/test'

test.use({ actionTimeout: 15000 })
const click = (page: Page, name: string) => page.getByRole('button', { name, exact: true }).click()
async function open(page: Page, id = 'ack-checkpoint') {
  await page.goto(`/practice/${id}#message-state`)
  await expect(page.getByTestId('message-save-status')).toHaveText('当前操作已保存')
}
async function answer(page: Page, effects: string, checkpoints: string, copies: string) {
  await page.getByRole('combobox', { name: '消息实验预测', exact: true }).selectOption('unknown')
  await page.getByRole('textbox', { name: '消息效果次数作答', exact: true }).fill(effects)
  await page.getByRole('textbox', { name: '消息 Checkpoint 作答', exact: true }).fill(checkpoints)
  await page.getByRole('textbox', { name: '消息确认副本作答', exact: true }).fill(copies)
  await page.getByRole('combobox', { name: '消息边界解释', exact: true }).selectOption('separate-boundaries')
  await click(page, '核对并保存消息结果')
  await expect(page.getByTestId('message-save-status')).toHaveText('当前操作已保存')
}
test('manual early ACK loses work, while atomic checkpoint survives crash and lost ACK', async ({ page }) => {
  test.setTimeout(90000)
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await open(page)
  await click(page, '生产并确认一条消息')
  await click(page, '递送 delivery-1')
  await expect(page.getByTestId('message-effects')).toHaveText('0')
  await click(page, '递送 ack-1')
  await click(page, 'Worker 崩溃')
  await click(page, '重启 Worker')
  await expect(page.getByTestId('message-acked')).toHaveText('1 / 1')
  await answer(page, '0', '0', '1')
  await expect(page.getByTestId('message-feedback')).toContainText('仍有任务没有业务效果')
  await expect(page.getByTestId('message-feedback')).not.toContainText('本关消息验证通过')
  await page.getByRole('combobox', { name: '消费者处理策略', exact: true }).selectOption('atomic')
  await click(page, '消费 ACK 丢失')
  await click(page, '生产并确认一条消息')
  await click(page, '递送 delivery-1')
  await click(page, '执行效果 delivery-1')
  await expect(page.getByTestId('message-effects')).toHaveText('1')
  await expect(page.getByTestId('message-checkpoints')).toHaveText('1')
  await click(page, '丢弃 ack-1')
  await click(page, 'Worker 崩溃')
  await page.getByRole('button', { name: /^推进下一次到期/ }).click()
  await expect(page.getByTestId('delivery-2')).toBeVisible()
  await click(page, '重启 Worker')
  await click(page, '递送 delivery-2')
  await click(page, '执行效果 delivery-2')
  await click(page, '递送 ack-2')
  await expect(page.getByTestId('message-effects')).toHaveText('1')
  await expect(page.getByRole('table', { name: '完整消息事件表', exact: true })).toContainText('跳过重复效果')
  await answer(page, '1', '1', '1')
  await expect(page.getByTestId('message-feedback')).toContainText('本关消息验证通过')
  await page.reload()
  await expect(page.getByTestId('message-effects')).toHaveText('1')
  await expect(page.getByTestId('message-feedback')).toContainText('本关消息验证通过')
  expect(errors).toEqual([])
})
