test('keeps simulation history separate and makes failed saves visible and retryable', async ({ page }) => {
  test.setTimeout(60_000)
  await page.addInitScript(() => {
    const original = IDBDatabase.prototype.transaction
    const flags = { fail: false }
    // Install before Dexie captures the native transaction function at open.
    IDBDatabase.prototype.transaction = function (...args: Parameters<typeof original>) {
      if (flags.fail && this.name === 'system-design-algorithm-labs' && args[1] === 'readwrite') throw new DOMException('test quota', 'QuotaExceededError')
      return original.apply(this, args)
    }
    Object.assign(window, { algorithmStorageFlags: flags })
  })
  await page.goto('/practice/service-queue-replicas')
  await page.getByRole('button', { name: '运行并检查', exact: true }).click()
  await expect(page.getByTestId('exercise-attempts')).toContainText('1 个副本')
  await open(page)
  await page.evaluate(() => { (window as unknown as { algorithmStorageFlags: { fail: boolean } }).algorithmStorageFlags.fail = true })
  await page.getByRole('combobox', { name: '你的预测', exact: true }).selectOption('uncertain')
  await page.getByRole('button', { name: '+ 新增 node-e', exact: true }).click()
  await page.getByRole('button', { name: '运行并记录', exact: true }).click()
  await expect(page.getByTestId('algorithm-save-status')).toContainText('未保存')
  await expect(page.getByTestId('algorithm-history').locator('details')).toHaveCount(1)
  await page.evaluate(() => { (window as unknown as { algorithmStorageFlags: { fail: boolean } }).algorithmStorageFlags.fail = false })
  await page.getByRole('button', { name: '重试保存当前实验', exact: true }).click()
  await expect(page.getByTestId('algorithm-save-status')).toHaveText('已保存到此浏览器')
  await page.goto('/practice/service-queue-replicas')
  await expect(page.getByTestId('exercise-attempts')).toContainText('1 个副本')
  await open(page)
  await expect(page.getByTestId('algorithm-history').locator('details')).toHaveCount(1)
  await expect(page.getByTestId('algorithm-feedback')).toContainText('操作完成，继续用证据解释')
})
