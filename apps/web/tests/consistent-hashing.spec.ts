import { expect, test, type Page } from '@playwright/test'
import { compare, distribute } from '../src/features/practice/distribution/model'
import { challenge, type Mode } from '../src/features/practice/distribution/lesson'
import type { Method } from '../src/features/practice/distribution/model'

test.use({ actionTimeout: 10_000 })

const title = '扩容时，哪些 key 需要换节点？'
async function open(page: Page) {
  await page.goto('/practice')
  await page.getByRole('link', { name: title, exact: true }).click()
  await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible()
  await expect(page.getByTestId('algorithm-save-status')).toHaveText('已保存到此浏览器')
}
async function solve(page: Page, mode: Mode, method: Method) {
  const draft = challenge(mode, method)
  const before = distribute(draft.input)
  draft.input.nodes = mode === 'add' ? [...draft.input.nodes, 'node-e'] : draft.input.nodes.filter((node) => node !== 'node-c')
  const after = distribute(draft.input)
  const comparison = compare(before, after)!
  const moved = after.assignments.find((item) => before.assignments.find((old) => old.key === item.key)?.owner !== item.owner)!
  await page.getByRole('combobox', { name: '你的预测', exact: true }).selectOption('uncertain')
  await page.getByRole('button', { name: mode === 'add' ? '+ 新增 node-e' : '移除 node-c', exact: true }).click()
  await page.getByRole('button', { name: '运行并记录', exact: true }).click()
  await expect(page.getByTestId('algorithm-feedback')).toContainText('操作完成，继续用证据解释')
  await expect(page.getByTestId('remapped-count')).toHaveText(comparison.remapped.toLocaleString())
  await page.getByLabel('发生变化的 key', { exact: true }).fill(moved.key)
  await page.getByLabel('需要重映射的 key 数', { exact: true }).fill(String(comparison.remapped))
  const local = comparison.transfers.every((item) => item.from === item.to || (mode === 'add' ? item.to === 'node-e' : item.from === 'node-c'))
  await page.getByRole('combobox', { name: '本次变化涉及哪些节点？', exact: true }).selectOption(local ? 'local' : 'spread')
  await page.getByRole('combobox', { name: '较少重映射能说明什么？', exact: true }).selectOption('separate')
  await page.getByLabel('你的复盘（保留原文，不自动判分）', { exact: true }).fill('需要分别观察归属变化和键数均衡。')
  await expect(page.getByTestId('algorithm-feedback')).toContainText('复盘有未提交的修改')
  await page.getByRole('button', { name: '检查解释并记录', exact: true }).click()
  await expect(page.getByTestId('algorithm-feedback')).toContainText('本次挑战通过')
  await expect(page.getByTestId('algorithm-save-status')).toHaveText('已保存到此浏览器')
}

test('completes all three controlled additions, a separate removal task, and restores evidence', async ({ page }) => {
  test.setTimeout(90_000)
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await open(page)
  await expect(page.getByRole('button', { name: '运行并记录', exact: true })).toBeDisabled()
  await solve(page, 'add', 'modulo')
  await page.getByRole('button', { name: '单 token 环', exact: true }).click()
  await expect(page.getByTestId('algorithm-feedback')).toContainText('有未运行的修改')
  await solve(page, 'add', 'ring')
  await page.getByRole('button', { name: '虚拟节点环', exact: true }).click()
  await solve(page, 'add', 'vnodes')
  await expect(page.getByLabel('学习进度')).toContainText('3 / 3 方法已验证')
  await page.getByRole('button', { name: '进入新数据集的移除节点挑战', exact: false }).click()
  await solve(page, 'remove', 'vnodes')
  await expect(page.getByLabel('学习进度')).toContainText('本题挑战已完成')
  await page.reload()
  await expect(page.getByTestId('algorithm-feedback')).toContainText('本次挑战通过')
  await expect(page.getByLabel('学习进度')).toContainText('本题挑战已完成')
  await expect(page.getByRole('textbox', { name: '你的复盘（保留原文，不自动判分）', exact: true })).toHaveValue('需要分别观察归属变化和键数均衡。')
  await expect(page.getByTestId('algorithm-history').locator('details')).toHaveCount(8)
  await expect(page.getByRole('button', { name: '撤销', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: '重置实验', exact: true }).click()
  await expect(page.getByTestId('algorithm-feedback')).toContainText('有未运行的修改')
  await expect(page.getByTestId('algorithm-history').locator('details')).toHaveCount(8)
  await page.getByRole('button', { name: '撤销', exact: true }).click()
  await expect(page.getByTestId('algorithm-feedback')).toContainText('本次挑战通过')
  await page.screenshot({ path: 'test-results/consistent-hashing-desktop.png', fullPage: true })
  expect(errors).toEqual([])
})

