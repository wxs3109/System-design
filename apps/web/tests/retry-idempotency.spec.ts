test('reports failed saves, retries persistence and restores executable command state', async ({ page }) => {
  await page.addInitScript(() => {
    const original = IDBDatabase.prototype.transaction
    const flags = { fail: false }
    IDBDatabase.prototype.transaction = function (...args: Parameters<typeof original>) {
      if (flags.fail && this.name === 'system-design-algorithm-labs' && args[1] === 'readwrite') throw new DOMException('test quota', 'QuotaExceededError')
      return original.apply(this, args)
    }
    Object.assign(window, { retryStorageFlags: flags })
  })
  await open(page)
  await page.evaluate(() => { (window as unknown as { retryStorageFlags: { fail: boolean } }).retryStorageFlags.fail = true })
  await button(page, '运行完整故障示例').click()
  await button(page, '核对并保存结果').click()
  await expect(page.getByTestId('retry-save-status')).toContainText('未保存')
  await expect(page.getByTestId('retry-task-count')).toHaveText('2 个任务')
  await expect(page.getByTestId('retry-history').locator('details')).toHaveCount(1)
  await page.evaluate(() => { (window as unknown as { retryStorageFlags: { fail: boolean } }).retryStorageFlags.fail = false })
  await button(page, '重试保存协议实验').click()
  await expect(page.getByTestId('retry-save-status')).toHaveText('当前操作已保存')
  await page.reload()
  await expect(page.getByTestId('retry-task-count')).toHaveText('2 个任务')
  await expect(page.getByTestId('retry-feedback')).toContainText('发现重复创建')
  await button(page, '清空操作重新开始').click()
  await button(page, '提交请求').focus()
  await page.keyboard.press('Enter')
  await expect(page.getByTestId('request-1')).toBeVisible()
})
