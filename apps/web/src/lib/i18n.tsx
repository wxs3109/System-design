const interpolate = (template: string, values: TranslationValues) => template.replace(/\{([A-Za-z0-9_]+)\}/g, (_match, key: string) => String(values[key] ?? `{${key}}`))

interface I18nValue {
  locale: Locale
  setLocale: (locale: Locale) => void
  t: Translate
}

const I18nContext = createContext<I18nValue | undefined>(undefined)

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>('en')

  useEffect(() => {
    const saved = window.localStorage.getItem(localeStorageKey)
    // Locale is a local UI preference and intentionally hydrates after the stable English server render.
    // eslint-disable-next-line react-hooks/set-state-in-effect
    if (saved === 'en' || saved === 'zh-CN') setLocaleState(saved)
  }, [])

  const setLocale = useCallback((next: Locale) => {
    setLocaleState(next)
    window.localStorage.setItem(localeStorageKey, next)
  }, [])

  useEffect(() => { document.documentElement.lang = locale }, [locale])

  const t = useCallback<Translate>((key, values = {}, fallback) => interpolate(locale === 'zh-CN' ? zhCN[key] ?? fallback ?? key : fallback ?? key, values), [locale])
  const value = useMemo(() => ({ locale, setLocale, t }), [locale, setLocale, t])
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export const useI18n = () => {
  const value = useContext(I18nContext)
  if (!value) throw new Error('useI18n must be used inside I18nProvider.')
  return value
}

export const localizedValue = (t: Translate, value: string, fallback = value) => t(`value.${value}`, {}, fallback)
